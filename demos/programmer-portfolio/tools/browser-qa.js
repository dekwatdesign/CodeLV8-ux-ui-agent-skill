async (page) => {
  const passed=[],errors=[];
  const check=(name,value)=>{if(!value)throw new Error(name);passed.push(name)};
  page.on('pageerror',e=>errors.push(e.message));
  const base='http://127.0.0.1:8768/demos/programmer-portfolio/';
  await page.goto(base);
  await page.waitForFunction(()=>document.querySelector('#scene').dataset.state==='ready');
  await page.evaluate(()=>document.fonts.ready);
  check('GLB loaded with animation clips',Number(await page.locator('#scene').getAttribute('data-clips'))>0);
  check('Local LINE Seed regular and bold loaded',await page.evaluate(()=>document.fonts.check('400 16px "LINE Seed"')&&document.fonts.check('700 16px "LINE Seed"')&&[...document.fonts].every(f=>f.status==='loaded')));
  const frame=Number(await page.locator('#scene').getAttribute('data-frame'));
  await page.waitForFunction(t=>Number(document.querySelector('#scene').dataset.frame)>t+.1,frame);
  check('Animation mixer advances in visible scene',true);
  await page.locator('#motion').click();
  const pausedFrame=await page.locator('#scene').getAttribute('data-frame');
  await page.waitForTimeout(250);
  check('Pause freezes animation timeline',await page.locator('#scene').getAttribute('data-frame')===pausedFrame);
  const still=await page.locator('canvas').screenshot();
  await page.locator('#motion').click();
  await page.waitForTimeout(350);
  const animated=await page.locator('canvas').screenshot();
  check('Resuming animation changes rendered canvas pixels',!still.equals(animated));
  await page.locator('#motion').click();
  const initial=await page.locator('canvas').screenshot();
  await page.locator('#rotate').click();await page.waitForTimeout(650);await page.locator('#rotate').click();
  check('Rotation changes rendered camera view',!initial.equals(await page.locator('canvas').screenshot()));
  await page.locator('#reset').click();
  check('Reset restores initial rendered view',initial.equals(await page.locator('canvas').screenshot()));
  for(const width of [1440,768,390,320]){
    await page.setViewportSize({width,height:1000});await page.evaluate(()=>scrollTo(0,0));await page.waitForTimeout(100);
    check('No document overflow at '+width,await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
    check('Scene canvas fits at '+width,await page.locator('canvas').evaluate(el=>el.width>0&&el.getBoundingClientRect().right<=innerWidth));
    await page.screenshot({path:'output/playwright/portfolio-'+width+'.png',fullPage:true});
  }
  await page.getByRole('button',{name:'ดูรายละเอียด Orbit',exact:true}).click();
  check('Project dialog opens with correct data',await page.locator('#project-dialog').evaluate(el=>el.open)&&await page.locator('#dialog-title').textContent()==='Orbit — จัดการงานให้เป็นระบบ');
  await page.locator('#project-dialog').screenshot({path:'output/playwright/portfolio-project-mobile.png'});
  check('Project modal fits mobile',await page.locator('#project-dialog').evaluate(el=>{const r=el.getBoundingClientRect();return r.left>=0&&r.right<=innerWidth&&r.height<=innerHeight}));
  await page.keyboard.press('Tab');
  check('Keyboard focus stays inside modal',await page.locator('#project-dialog').evaluate(el=>el.contains(document.activeElement)));
  await page.keyboard.press('Escape');
  check('Escape closes dialog and returns focus',await page.locator('[data-project=orbit]').evaluate(el=>el===document.activeElement)&&!await page.locator('#project-dialog').evaluate(el=>el.open));
  await page.getByRole('button',{name:'ดูรายละเอียด Mellow',exact:true}).focus();await page.keyboard.press('Enter');
  check('Keyboard opens second project',await page.locator('#dialog-title').textContent()==='Mellow — ประสบการณ์ร้านค้าออนไลน์');
  await page.getByRole('button',{name:'กลับไปดูผลงาน',exact:true}).click();
  await page.locator('#contact-open').click();
  check('Contact dialog opens',await page.locator('#contact-dialog').evaluate(el=>el.open));
  await page.evaluate(()=>{Object.defineProperty(navigator,'clipboard',{configurable:true,value:{writeText:()=>Promise.reject(new Error('denied'))}})});
  await page.locator('#copy-email').click();
  check('Clipboard failure offers manual copy',(await page.locator('#copy-status').textContent()).includes('คัดลอกอัตโนมัติไม่ได้'));
  await page.keyboard.press('Escape');
  await page.setViewportSize({width:1440,height:1000});
  await page.emulateMedia({reducedMotion:'reduce'});await page.goto(base);await page.waitForFunction(()=>document.querySelector('#scene').dataset.state==='ready');
  check('Reduced motion starts animation paused',await page.locator('#motion').getAttribute('aria-pressed')==='true');
  await page.screenshot({path:'output/playwright/portfolio-reduced-motion.png'});
  await page.emulateMedia({reducedMotion:'no-preference'});
  await page.route('**/studio.glb',route=>route.abort());await page.goto(base);
  await page.waitForFunction(()=>document.querySelector('#scene').dataset.state==='fallback');
  check('Failed GLB load shows usable poster',await page.locator('#scene-poster').isVisible()&&await page.locator('#motion').isDisabled());
  check('Fallback retains project UI',await page.getByRole('button',{name:'ดูรายละเอียด Orbit',exact:true}).isEnabled());
  await page.screenshot({path:'output/playwright/portfolio-fallback.png'});
  await page.unroute('**/studio.glb');await page.goto(base);await page.waitForFunction(()=>document.querySelector('#scene').dataset.state==='ready');
  await page.locator('#motion').click();await page.screenshot({path:'output/playwright/portfolio-desktop.png',fullPage:true});
  check('No uncaught browser errors',errors.length===0);
  return {passed,count:passed.length,errors};
}
